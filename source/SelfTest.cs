using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Collections.Generic;
using System.Windows;
using System.Windows.Media;
using System.Windows.Media.Imaging;
using System.Windows.Controls;
using System.Reflection;

namespace Chitoge {
public static class SelfTest {
    static List<string> lines=new List<string>();
    static void Check(bool b,string text){lines.Add((b?"PASS ":"FAIL ")+text);if(!b)throw new Exception(text);}
    public static int Run(string[] args) {
        string dir=Path.GetFullPath(args.Length>1?args[1]:Path.Combine(Program.Home,"test-results"));
        Directory.CreateDirectory(dir);
        try {
            var app=new Application();var pet=new PetWindow(false);
            Check(pet.Frames.Sum(a=>a.Length)==73,"All 73 original frames loaded, including 16 gaze directions");
            Check(pet.Reaction.PixelWidth>0,"New handkerchief image loaded");
            string probe=Path.Combine(dir,"chitoge-recycle-test-"+Guid.NewGuid().ToString("N")+".txt");
            File.WriteAllText(probe,"Disposable Chitoge recycle test, generated by the application.",Encoding.UTF8);
            var data=new DataObject(DataFormats.FileDrop,new[]{probe});
            var enter=DragArgs(data,pet,DragDrop.PreviewDragEnterEvent);pet.RaiseEvent(enter);
            Check(pet.IsHoveringForTests&&enter.Effects==DragDropEffects.Move,"File drag-enter switches to handkerchief reaction");
            pet.RaiseEvent(DragArgs(data,pet,DragDrop.PreviewDragLeaveEvent));
            Check(!pet.IsHoveringForTests,"Drag-leave restores normal state");
            bool asked=false;pet.ConfirmForTests=paths=>{asked=true;return false;};
            var drop=DragArgs(data,pet,DragDrop.PreviewDropEvent);pet.RaiseEvent(drop);
            Check(asked&&!pet.IsHoveringForTests&&File.Exists(probe),"Drop cancellation keeps original file and restores state");
            Check(drop.Effects==DragDropEffects.None,"Drop source is never instructed to delete its own originals");
            var textDrag=DragArgs(new DataObject(DataFormats.Text,"not a file"),pet,DragDrop.PreviewDragEnterEvent);pet.RaiseEvent(textDrag);
            Check(textDrag.Effects==DragDropEffects.None&&!pet.IsHoveringForTests,"Non-file drops rejected");
            Check(FilePolicy.Validate(new[]{probe,probe}).Length==1,"Duplicate file paths deduplicated");
            bool rejected=false;try{FilePolicy.Validate(new[]{Path.GetPathRoot(dir)});}catch(IOException){rejected=true;}Check(rejected,"Drive root rejected");
            rejected=false;try{FilePolicy.Validate(new[]{Program.Home});}catch(IOException){rejected=true;}Check(rejected,"Application folder rejected");
            rejected=false;try{FilePolicy.Validate(new[]{@"\\server\share\file.txt"});}catch(IOException){rejected=true;}Check(rejected,"Network path rejected");
            var sink=new RecycleSink();Check(sink.PreDeleteItem(0,null)<0&&sink.Blocked,"Non-recycle shell callback blocked");
            string folder=Path.Combine(dir,"chitoge-folder-test-"+Guid.NewGuid().ToString("N"));Directory.CreateDirectory(folder);string child=Path.Combine(folder,"中文 文件.txt");File.WriteAllText(child,"nested-test");
            Check(FilePolicy.Validate(new[]{folder,child}).Length==1,"Folder and child collapsed to one operation");
            var r=RecycleService.Send(new[]{probe,folder},IntPtr.Zero);
            if(r.Completed==0 && r.Aborted && r.Error.Contains("0x202")) {
                Check(File.Exists(probe)&&File.Exists(child),"Unavailable Recycle Bin: operation refused and both test items preserved");
                lines.Add("UNVERIFIED successful live recycling: this isolated Windows account cannot access its Recycle Bin. "+r.Error);
            } else {
                Check(r.Completed==2&&!r.Aborted&&r.Error=="","Two items recycled through real Windows shell; "+r.Error);
                Check(!File.Exists(probe)&&!Directory.Exists(folder),"Original test paths removed");
                Check(r.StoredPaths.Count==2&&r.StoredPaths.All(p=>p.IndexOf("$Recycle.Bin",StringComparison.OrdinalIgnoreCase)>=0),"Shell returned real Recycle Bin locations");
                Check(File.ReadAllText(r.StoredPaths[0]).Contains("Disposable Chitoge"),"Recycled file bytes verified");
                Check(File.ReadAllText(Path.Combine(r.StoredPaths[1],"中文 文件.txt"))=="nested-test","Recycled folder child bytes verified");
                lines.AddRange(r.StoredPaths.Select(p=>"RECYCLED_TEST_ITEM "+p));
            }
            var preview=new StackPanel{Orientation=Orientation.Horizontal,Background=PetWindow.Brush("#F5F0F4"),Margin=new Thickness(0)};
            foreach(var entry in new[]{new{Title="日常陪伴",Image=pet.Frames[0][0]},new{Title="文件拖入 · 咬手帕",Image=pet.Reaction}}) {
                var panel=new StackPanel{Width=280,Margin=new Thickness(22)};
                panel.Children.Add(new TextBlock{Text=entry.Title,FontFamily=new FontFamily("Microsoft YaHei UI"),FontSize=18,Foreground=PetWindow.Brush("#563E51"),HorizontalAlignment=HorizontalAlignment.Center,Margin=new Thickness(0,14,0,22)});
                panel.Children.Add(new Image{Source=entry.Image,Width=240,Height=260,Stretch=Stretch.Uniform});preview.Children.Add(panel);
            }
            Render(preview,648,370,Path.Combine(dir,"preview.png"));
            var dialog=new ConfirmWindow(null,new[]{@"C:\示例文件\课堂笔记（测试）.txt",@"C:\示例文件\旧草稿"});
            Render((FrameworkElement)dialog.Content,490,320,Path.Combine(dir,"confirmation.png"));dialog.Close();pet.Close();
            lines.Add("PASS UI previews rendered");
            File.WriteAllLines(Path.Combine(dir,"test-report.txt"),lines,Encoding.UTF8);return 0;
        }catch(Exception ex){lines.Add(ex.ToString());File.WriteAllLines(Path.Combine(dir,"test-report.txt"),lines,Encoding.UTF8);return 1;}
    }
    static void Render(FrameworkElement element,int w,int h,string file){element.Measure(new Size(w,h));element.Arrange(new Rect(0,0,w,h));element.UpdateLayout();var bitmap=new RenderTargetBitmap(w,h,96,96,PixelFormats.Pbgra32);bitmap.Render(element);var encoder=new PngBitmapEncoder();encoder.Frames.Add(BitmapFrame.Create(bitmap));using(var output=File.Create(file))encoder.Save(output);}
    static DragEventArgs DragArgs(IDataObject data,DependencyObject target,RoutedEvent evt){
        var ctor=typeof(DragEventArgs).GetConstructor(BindingFlags.Instance|BindingFlags.NonPublic,null,new[]{typeof(IDataObject),typeof(DragDropKeyStates),typeof(DragDropEffects),typeof(DependencyObject),typeof(Point)},null);
        var a=(DragEventArgs)ctor.Invoke(new object[]{data,DragDropKeyStates.LeftMouseButton,DragDropEffects.Move,target,new Point(120,150)});a.RoutedEvent=evt;return a;
    }
}
}
